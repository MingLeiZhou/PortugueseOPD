def block(n):
    return f'{INTRO[n]}\n\n![Figure {n}](figures_final/fig{n:02d}_{STEMS[n]}.png)\n\n{CAPTIONS[n]}'

def main():
    path=ROOT/'paper/PT60_Sep16.MD';md=path.read_text()
    if 'figures_final/' in md:
        print('Already reduced; manuscript preserved.');return
    before_tables=re.findall(r'^\|[^\n]*',md,re.M)
    pattern=r'!\[Figure (\d+)\]\([^)]+\)\s*\n\*\*Figure \1[^\n]*'
    assert len(re.findall(pattern,md))==18
    def replace(m):
        old=int(m[1])
        # Old 14 is merged into 11's location; scope figure moves to Validation Scope.
        if old in DELETE or old in [13,14]:return ''
        return block(MAPPING[old])
    md=re.sub(pattern,replace,md)
    marker='# 5. Application Example and Interactive Visualization'
    assert marker in md
    md=md.replace(marker,block(8)+'\n\n'+marker,1)
    md=re.sub(r'\n{4,}','\n\n\n',md)
    assert re.findall(r'^\|[^\n]*',md,re.M)==before_tables
    assert [int(n) for n in re.findall(r'!\[Figure (\d+)\]',md)]==list(range(1,12))
    path.write_text(md)
    print('Reduced 18 figures to 11; all table rows preserved verbatim.')

if __name__=='__main__':main()
